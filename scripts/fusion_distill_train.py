#!/usr/bin/env python
"""END-TO-END FUSION DISTILLATION — LoRA-fine-tune the LM (14B) so the FUSED SLM+LM output reproduces the
full-context LM-teacher (see LORA_FUSION_FT_PLAN.md).

In 'ours', the LM sees query+reasoning but NEVER the context, so it is off-distribution. We teacher-force the
teacher's [reasoning + Final Answer] token sequence through the ACTUAL fusion and train ONLY the LM-LoRA:

  slm_logits = SLM( [SLM_prefix(full context) ++ y] )   # frozen, no_grad
  lm_logits  = LM(  [LM_prefix(query only)   ++ y] )     # LoRA, grad
  fused      = lam * slm_logits + (1-lam) * lm_logits    # identical weighted-sum + lam as inference
  loss       = CE(fused, y)  over completion tokens only  # backprop -> LoRA only

The two prefixes are built with the EVAL harness's OWN prompt functions, so train == inference prompt.
Only the LoRA updates -> it learns to COMPLEMENT the frozen SLM so their fusion equals the teacher.

Target y = the teacher log's `teacher.text` (generated by the SAME teacher that is the eval ceiling), rendered
the way the eval pipeline renders it and otherwise UNEDITED — the goal is only that SLM+LM output matches the
teacher's output on any input under any prompt, so the teacher's behaviour is cloned, never curated (no gold
filter, no 'must have reasoned' filter; both exist only as explicitly labelled ablations).

Efficiency: SLM forward is no_grad (no activation memory); the LM grad-forward is over [query ++ ~200-tok
completion] ~= 250 tokens, so 14B-base bf16 (28GB) + 3B (6GB) + tiny LoRA/AdamW fits ONE 96GB GH200.
"""
